function [singleFamilies, pairFamilies] = ...
        allelicStateTreeCSFunctionFamilies(instance)
%ALLELICSTATETREECSFUNCTIONFAMILIES Camin-Sokal transformation families.
%   SINGLES contains one family for each unique alignment column:
%       g_c(s)=s, h_c(s)=-s-M^c.
%
%   For every unordered unique-column pair c1<c2, let S be the observed set
%   of joint states 00,01,10,11. If |S|=1, no pair family is generated. For
%   every cached X-table hierarchy H matching S, this function returns
%       g_H(s)=s,
%       h_H(s)=s-2^d_H*s-z^H,
%   where z^H_i=kappa_H(M_i,c1 M_i,c2).

alignment = validateAlignment(instance);
[patterns, sourceColumns] = unique(alignment.', 'rows', 'stable');
familyCount = size(patterns, 1);
singleTemplate = struct('id', '', 'g', @(s) s, 'h', @(s) s, ...
    'familyType', 'single_column', 'M', zeros(0, 1), ...
    'sourceColumn', 0, 'collisionDepth', uint8(1), ...
    'collisionZ', zeros(0, 1));
singleFamilies = repmat(singleTemplate, familyCount, 1);
for c = 1:familyCount
    column = double(patterns(c, :).');
    singleFamilies(c) = struct( ...
        'id', sprintf('alignment_pattern_%d', c), ...
        'g', @(s) s, 'h', @(s) -s - column, ...
        'familyType', 'single_column', 'M', column, ...
        'sourceColumn', sourceColumns(c), ...
        'collisionDepth', uint8(1), 'collisionZ', column);
end
if nargout < 2
    return;
end
catalog = loadPairAllelicStateTreeCatalog();

matchingRows = cell(familyCount, familyCount);
stateCodes = cell(familyCount, familyCount);
observedMasks = zeros(familyCount, familyCount, 'uint8');
pairFamilyCount = 0;
for c1 = 1:familyCount - 1
    for c2 = c1 + 1:familyCount
        codes = uint8(2*patterns(c1, :) + patterns(c2, :));
        observed = unique(codes, 'sorted');
        if isscalar(observed)
            continue;
        end
        mask = uint8(sum(bitshift(uint8(1), observed)));
        rows = find(catalog.stateMask == mask);
        if isempty(rows)
            error('padic:allelicStateCatalogCoverage', ...
                'No X-table rows match observed-state mask %d.', mask);
        end
        matchingRows{c1, c2} = rows;
        stateCodes{c1, c2} = codes;
        observedMasks(c1, c2) = mask;
        pairFamilyCount = pairFamilyCount + numel(rows);
    end
end

template = struct('id', '', 'g', @(s) s, 'h', @(s) s, ...
    'familyType', 'allelic_state_tree_pair', ...
    'M1', zeros(0, 1), 'M2', zeros(0, 1), ...
    'columnPair', zeros(1, 2), 'sourceColumns', zeros(1, 2), ...
    'observedJointStates', '', 'observedStateMask', uint8(0), ...
    'catalogRow', uint16(0), 'orientationIndex', uint16(0), ...
    'orderedRootedTree', '', 'kappa', nan(1, 4), ...
    'd_H', uint8(0), 'z', zeros(0, 1), ...
    'collisionDepth', uint8(0), 'collisionZ', zeros(0, 1));
pairFamilies = repmat(template, pairFamilyCount, 1);
familyIndex = 0;
for c1 = 1:familyCount - 1
    column1 = double(patterns(c1, :).');
    for c2 = c1 + 1:familyCount
        rows = matchingRows{c1, c2};
        if isempty(rows)
            continue;
        end
        column2 = double(patterns(c2, :).');
        codes = double(stateCodes{c1, c2}) + 1;
        for catalogRow = reshape(rows, 1, [])
            familyIndex = familyIndex + 1;
            kappa = catalog.kappa(catalogRow, :);
            z = reshape(kappa(codes), [], 1);
            d_H = catalog.d_H(catalogRow);
            pairFamilies(familyIndex) = struct( ...
                'id', sprintf('allelic_pair_%d_%d_H_%d', ...
                    c1, c2, catalog.orientationIndex(catalogRow)), ...
                'g', @(s) s, ...
                'h', @(s) s - 2^double(d_H)*s - z, ...
                'familyType', 'allelic_state_tree_pair', ...
                'M1', column1, 'M2', column2, ...
                'columnPair', [c1, c2], ...
                'sourceColumns', [sourceColumns(c1), sourceColumns(c2)], ...
                'observedJointStates', ...
                    catalog.observedJointStates{catalogRow}, ...
                'observedStateMask', observedMasks(c1, c2), ...
                'catalogRow', uint16(catalogRow), ...
                'orientationIndex', catalog.orientationIndex(catalogRow), ...
                'orderedRootedTree', ...
                    catalog.orderedRootedTree{catalogRow}, ...
                'kappa', kappa, 'd_H', d_H, 'z', z, ...
                'collisionDepth', d_H, 'collisionZ', z);
        end
    end
end
end

function alignment = validateAlignment(instance)
if ~isstruct(instance) || ~isscalar(instance) || ...
        ~isfield(instance, 'alignment') || isempty(instance.alignment) || ...
        ~ismatrix(instance.alignment)
    error('padic:csInstance', 'A CS instance must contain an alignment field.');
end
if ~(islogical(instance.alignment) || isnumeric(instance.alignment)) || ...
        any(instance.alignment(:) ~= 0 & instance.alignment(:) ~= 1)
    error('padic:binaryAlignment', 'The CS alignment must be a binary matrix.');
end
alignment = logical(instance.alignment);
end
